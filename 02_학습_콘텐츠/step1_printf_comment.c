/**
 * @file step1_printf_comment.c
 * @brief Step 1: printf 출력 서식과 주석(Comment) 작성법
 * @details 화면에 안내 문구를 깔끔하게 출력하고, 코드의 의미를 설명하는 주석을 작성합니다.
 */

#include <stdio.h>

int main(void)
{
    // [단일행 주석] 학생 정보 및 프로그램 목적을 기술합니다.
    /*
     * [다중행 주석]
     * 작성자: 동아마이스터고 1학년
     * 과제명: Step 1 기본 출력 및 주석 작성
     */

    // 1. 단순 문자열 출력 (\n은 줄바꿈 escape sequence)
    printf("=== 동아마이스터고 C언어 기초 실습 ===\n");

    // 2. 띄어쓰기와 콜론(:) 위치에 주의하여 프롬프트 출력
    // (주의: 줄바꿈 \n을 붙이지 않아야 바로 옆에 입력을 받을 수 있습니다!)
    printf("성적 입력 하세요:");

    // 3. 테스트용 출력
    printf("\n[확인] 프롬프트 출력이 정상적으로 완료되었습니다.\n");

    return 0;
}
