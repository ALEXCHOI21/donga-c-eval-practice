/**
 * @file step5_solution_sample.c
 * @brief Step 5 모범 답안 예시 (기준 점수: 80점 기준, 타 반 변형 대비 가능)
 * @details 동아마이스터고 C언어 3회차 수행평가 만점 기준 완성본
 */

#include <stdio.h>

int main(void)
{
    // 1. 성적 저장을 위한 정수형 변수 선언 및 초기화
    int score = 0;

    // 2. 성적 입력 안내 프롬프트 출력 (띄어쓰기 및 콜론 위치 필수 준수)
    printf("성적 입력 하세요:");

    // 3. scanf_s를 활용한 정수 안전 입력 (주소 연산자 & 필수)
    scanf_s("%d", &score);

    // 4. 관계 연산자(>=)와 if-else 문을 통한 합격/불합격 판정
    // [참고] 반별 기준 점수: 3-5반(60점), 3-7반(80점), 3-8반(75점), 3-9반(85점)
    if (score >= 80)
    {
        // 80점 이상일 경우 실행되는 블록
        printf("합격을 축하합니다!\n");
    }
    else
    {
        // 80점 미만일 경우 실행되는 블록
        printf("불합격입니다 화이팅!!\n");
    }

    return 0; // 프로그램 정상 종료
}
